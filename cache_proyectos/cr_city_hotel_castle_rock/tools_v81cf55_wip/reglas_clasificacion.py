def clasificar(cat):
    """{id: decisión} para cada regla del catálogo que tiene decisión."""
    out = {}
    for r in cat:
        rid = r["id"]
        base = rid.split("~")[0]
        if base in POR_ID:
            out[rid] = POR_ID[base]
            continue
        txt = r["titulo"] + " " + r["texto"]
        for pref, rx, dec in REGLAS_TEXTO:
            if any(rid.startswith(p) for p in pref.split("|")) and re.search(rx, txt):
                out[rid] = dec
                break
    return out


